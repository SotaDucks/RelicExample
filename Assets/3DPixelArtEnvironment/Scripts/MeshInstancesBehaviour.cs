namespace Environment.Instancing
{
    using UnityEngine;
    using System;

    using System.Collections.Generic;
    using Environment.Utilities;

    /// <summary>
    /// Instances behaviour to generate on surfaces of meshes.
    /// </summary>
    [RequireComponent(typeof(MeshFilter), typeof(MeshRenderer))]
    public class MeshInstancesBehaviour : InstancesBehaviour
    {
        [Header("Sub Mesh Details")]
        public bool UseSubMesh = false;
        public int SubMeshIndex = 0;

        [Header("Instance Settings")]
        [Tooltip("Surface area per instance in mesh-local units. Smaller values create more instances.")]
        public float Density = 1f;
        [Min(1), Tooltip("Maximum instances generated by this mesh, protecting against accidental tiny Density values.")]
        public int MaxInstances = 100000;
        public InstancingSettings[] InstancingSettings;


        /// <summary>
        /// Calculates the bounds for the instances used for culling by Unity.
        /// </summary>
        public override Bounds CalculateInstancesBounds()
        {
            var rendererBounds = this.GetComponent<MeshRenderer>().bounds;
            var diff = this.transform.position - rendererBounds.center;
            var absDiff = new Vector3(Mathf.Abs(diff.x),
                                      Mathf.Abs(diff.y),
                                      Mathf.Abs(diff.z));

            return new Bounds(this.transform.position, (rendererBounds.extents + absDiff) * 2f);
        }

        /// <summary>
        /// Implementation of instance data logic for instances behaviour.
        /// </summary>
        public override Dictionary<InstancingSettings, List<InstanceData>> GetInstanceData()
        {
            if (this.InstancingSettings == null || this.InstancingSettings.Length == 0)
            {
                Debug.LogWarning("Instancing settings should be defined the Unity Editor.");
                return null;
            }

            foreach (var settings in this.InstancingSettings)
            {
                if (settings.Scale <= 0f || settings.Material == null || settings.Mesh == null)
                {
                    Debug.LogError("The given Instance Configurations should have a material, mesh and a scale larger than 0");
                    return null;
                }
            }

            var mesh = this.GetComponent<MeshFilter>().sharedMesh;
            if (mesh == null || !mesh.isReadable)
            {
                Debug.LogWarning("Leaf generation requires a mesh with Read/Write enabled in its model import settings.", this);
                return null;
            }

            if (this.UseSubMesh && (this.SubMeshIndex < 0 || this.SubMeshIndex >= mesh.subMeshCount))
            {
                Debug.LogWarning("The selected sub mesh does not exist. Leaf generation was skipped; select the canopy sub mesh.", this);
                return null;
            }

            Mesh samplingMesh = null;
            try
            {
                if (this.UseSubMesh)
                {
                    samplingMesh = new Mesh
                    {
                        // Imported models can have more than 65,535 vertices. Retain their
                        // index format before assigning triangles so indices do not wrap.
                        indexFormat = mesh.indexFormat,
                        vertices = mesh.vertices,
                        triangles = mesh.GetTriangles(this.SubMeshIndex)
                    };
                    mesh = samplingMesh;
                }

                var instanceData = RandomMeshInstanceData(mesh, this.Density, this.InstancingSettings, this.MaxInstances);
                return DivideInstanceData(instanceData, this.InstancingSettings);
            }
            finally
            {
                if (samplingMesh != null)
                {
                    if (Application.isPlaying) Destroy(samplingMesh);
                    else DestroyImmediate(samplingMesh);
                }
            }
        }

        /// <summary>
        /// Gets random mesh instance data on a mesh.
        /// </summary>
        public static InstanceData[] RandomMeshInstanceData(Mesh mesh, float density, InstancingSettings[] configurations, int maxInstances = 100000)
        {
            if (mesh == null || density <= 0 || float.IsNaN(density) || float.IsInfinity(density)
                || maxInstances <= 0 || configurations == null || configurations.Length == 0)
            {
                return null;
            }

            var area = MeshUtilities.GetMeshArea(mesh);
            if (area <= 0 || float.IsNaN(area) || float.IsInfinity(area)) return null;

            var requestedAmount = Math.Ceiling((double)area / density);
            var instanceAmount = (int)Math.Min(requestedAmount, maxInstances);
            if (requestedAmount > maxInstances)
            {
                Debug.LogWarning($"Leaf generation capped at {maxInstances:N0} instances (requested {requestedAmount:N0}). Increase Density to reduce the amount.");
            }

            var samples = MeshUtilities.RandomMeshPoints(mesh, instanceAmount);

            var data = new InstanceData[samples.Length];

            for (var i = 0; i < samples.Length; i++)
            {
                var (vertex, normal) = samples[i];

                var instance = new InstanceData
                {
                    TRS = Matrix4x4.TRS(
                        vertex,
                        Quaternion.identity,
                        Vector3.one
                    ),
                    Normal = normal
                };
                data[i] = instance;
            }

            return data;
        }
    }
}
